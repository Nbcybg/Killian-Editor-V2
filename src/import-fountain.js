// ที่มา: ลองนำเข้าไฟล์ .fountain ตามสเปกบนแอปจริง — ตัวนำเข้าส่งข้อความเข้า `parseScript()` ตรง ๆ
// ซึ่งเป็นตัวอ่าน "ไวยากรณ์ของ Killian" ไม่ใช่ Fountain มาตรฐาน ของที่สองภาษานี้เขียนไม่เหมือนกันจึงเพี้ยน:
//   · `[[โน้ตของผู้เขียน]]`  → ที่นี่ `[[ชื่อ]]` คือ **ลิงก์เอนทิตี้ของ Wiki** — โน้ตโผล่กลางบรรยายเป็นลิงก์
//   · `/* boneyard */`        → เนื้อที่ผู้เขียนตัดทิ้งแล้ว กลับมาเป็นบรรยายในบท
//   · `> กึ่งกลาง <`           → กลายเป็นทรานซิชันที่มี `<` ค้างท้าย
//   · `~เนื้อเพลง`             → มี `~` ค้างหน้าบรรทัด
//   · `===` (ขึ้นหน้าใหม่)     → ที่นี่ใช้ `---`
//   · `ชื่อ ^` (บทพูดคู่)      → ชื่อตัวละครกลายเป็น "ชื่อ ^" (นับเป็นตัวละครอีกคน)
// ตัวนี้แปลงเฉพาะของที่ต่างกัน **ก่อน** ส่งเข้า parseScript — ที่เหลือ (หัวฉาก · ชื่อ · วงเล็บ · ทรานซิชัน
// · `#` หัวข้อ · `=` เรื่องย่อ · ตัวเน้น) สองภาษาเขียนเหมือนกันอยู่แล้ว
//
// ไม่ import อะไรเลย — unit test ด้วย node ได้ตรง ๆ (test/import-fountain.test.cjs)

/**
 * @param {string} text ข้อความ Fountain (ตัดหน้าปกออกแล้ว)
 * @param {{notes?:boolean}} [opts] notes = แปลง `[[…]]` เป็นบรรทัดโน้ต (`/// …`)
 *   ใช้กับไฟล์ `.fountain` เท่านั้น — ไฟล์ `.txt` อาจเป็นบทที่เขียนในโปรแกรมนี้เอง ซึ่ง `[[ชื่อ]]` คือลิงก์จริง
 * @returns {string}
 */
export function fountainToK2(text, opts = {}) {
  let src = String(text == null ? '' : text).replace(/\r\n?/g, '\n');
  // boneyard — ผู้เขียนตัดทิ้งแล้ว ไม่ใช่เนื้อบท (กินได้หลายบรรทัด)
  // บล็อกที่กินทั้งบรรทัด: เอาบรรทัดว่างที่ตามมาออกด้วยหนึ่งบรรทัด (ไม่งั้นเหลือช่องว่างซ้อนสามบรรทัดตรงรอยตัด)
  src = src.replace(/\n[ \t]*\/\*[\s\S]*?\*\/[ \t]*\n(?:[ \t]*\n)?/g, '\n')
           .replace(/\/\*[\s\S]*?\*\//g, '');
  // โน้ตที่คร่อมหลายบรรทัด → บรรทัดเดียว (โน้ตของที่นี่เป็นบล็อกบรรทัดเดียว)
  if (opts.notes) src = src.replace(/\[\[([\s\S]*?)\]\]/g, (m, a) => '[[' + a.replace(/\s*\n\s*/g, ' ') + ']]');
  const out = [];
  for (const raw of src.split('\n')) {
    const s = raw.trim();
    if (/^={3,}$/.test(s)) { out.push('---'); continue; }             // ขึ้นหน้าใหม่
    let m = /^>\s*(\S.*?)\s*<$/.exec(s);
    if (m) { out.push('!' + m[1]); continue; }                        // กึ่งกลาง → บรรยาย (บังคับ กันถูกเดาเป็นชื่อ)
    if (/^~[^~]+$/.test(s)) { out.push('!*' + s.slice(1).trim() + '*'); continue; }   // เนื้อเพลง → ตัวเอียง
    let line = raw;
    // บทพูดคู่: `ชื่อ ^` — ที่นี่ไม่มีบทพูดคู่ · เก็บชื่อไว้ ตัด ^ ทิ้ง (ต้องไม่ใช่ตัวยก `x^2^`)
    m = /^(.*\S)\s*\^$/.exec(line);
    if (m && !m[1].includes('^')) line = m[1];
    if (opts.notes && line.includes('[[')) {
      const notes = [];
      const rest = line.replace(/\[\[(.*?)\]\]/g, (x, a) => { if (a.trim()) notes.push(a.trim()); return ''; });
      if (rest.trim()) out.push(rest.replace(/[ \t]{2,}/g, ' ').replace(/\s+$/, ''));
      for (const n of notes) out.push('/// ' + n);
      continue;
    }
    out.push(line);
  }
  return out.join('\n');
}
