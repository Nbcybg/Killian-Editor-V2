// ผู้ใช้: *"bug ใน คุณสมบัติ ของ planner มันเกิดอาการเรียกว่า auto refresh เมื่อเราพิมพ์แล้วจะดีดออก
//          เพราะโดน refresh ดังนั้นควรจะให้พิมพ์เสร็จก่อนถึง refresh"*
//
// แผงคุณสมบัติวาดตัวเองใหม่ทั้งแผง (`container.innerHTML = ''` แล้วสร้างใหม่หมด) ทุกครั้งที่
// ข้อมูลการ์ดเปลี่ยน · แต่ "ข้อมูลการ์ดเปลี่ยน" ก็คือผลของการพิมพ์ในแผงนั้นเอง →
// พิมพ์ไปสามตัวอักษร ช่องที่กำลังพิมพ์อยู่ถูกลบทิ้งแล้วสร้างใหม่ โฟกัสหลุด เคอร์เซอร์หาย
// (แถบเลื่อนขนาดตัวอักษร/ความจางก็โดนเหมือนกัน — ลากอยู่ดี ๆ ตัวแถบหายไปจากใต้เมาส์)
//
// กฎ: **ห้ามวาดใหม่ขณะที่โฟกัสอยู่ในแผง** — เก็บคำขอล่าสุดไว้ก่อน แล้วค่อยวาดเมื่อผู้ใช้ปล่อยมือ
// (โฟกัสออกจากแผง) · ไปคลิกอย่างอื่นเมื่อไหร่ ช่องในแผงก็หลุดโฟกัสก่อนเสมอ คำขอที่พักไว้จึงถูกวาดทันที
//
// แยกเป็นโมดูลของตัวเองเพราะเป็น "การตัดสินใจ" ล้วน ๆ — เทสได้โดยไม่ต้องมีเบราว์เซอร์

/** ป้ายระบุว่าแผงกำลังแสดงอะไรอยู่ — คนละป้าย = คนละเรื่อง วาดใหม่ได้เลย */
export function propsKey(ctx) {
  if (!ctx || !ctx.mode) return 'none';
  const d = ctx.data;
  const id = d && typeof d === 'object' ? (d.id || '') : String(d || '');
  return ctx.mode + ':' + (Array.isArray(d) ? d.join('+') : id);
}

/**
 * ควร "พัก" การวาดใหม่ไว้ก่อนไหม
 *
 * @param {Element} container กรอบของแผง
 * @param {Element} active    element ที่ถือโฟกัสอยู่ (`document.activeElement`)
 * @param {string} nextKey    ป้ายของสิ่งที่กำลังจะวาด
 * @param {string} lastKey    ป้ายของสิ่งที่วาดไว้อยู่
 * @returns {boolean} true = พักไว้ก่อน (ผู้ใช้ยังมือไม่ว่าง)
 */
export function shouldDeferRender(container, active, nextKey, lastKey) {
  if (!container || !active) return false;
  if (typeof container.contains !== 'function') return false;
  if (!container.contains(active)) return false;      // โฟกัสไม่ได้อยู่ในแผง = วาดได้เลย
  // ★ ไม่เทียบว่าเป็นวัตถุตัวเดิมไหม — **โฟกัสอยู่ในแผง = ผู้ใช้ยังมือไม่ว่าง** จบแค่นั้น
  //
  // รอบแรกเทียบป้ายด้วย แล้วยังพังอยู่: พิมพ์ทีหนึ่ง → การ์ดถูกวาดใหม่ → fabric ยิง
  // `selection:cleared` แล้ว `selection:created` ตามมา → แผงถูกสั่งวาดเป็น "ไม่ได้เลือกอะไร"
  // (ป้าย `none`) ก่อนจะกลับมาเป็นการ์ดใบเดิม · ป้ายไม่ตรงสักรอบ ด่านจึงไม่เคยกั้นอะไรเลย
  //
  // ไปคลิกการ์ดใบอื่นก็ยังถูกต้อง: กดเมาส์บนกระดาน = ช่องในแผงหลุดโฟกัสก่อนเสมอ
  // คำขอที่พักไว้จึงถูกวาดทันทีด้วยข้อมูลล่าสุด (ดู `_pending` ฝั่ง planner-props.js)
  //
  // ทุกตัวควบคุมนับหมด ไม่ใช่แค่ช่องพิมพ์ — ลากแถบเลื่อนอยู่แล้วโดนวาดใหม่ก็ขาดเหมือนกัน
  return true;
}
