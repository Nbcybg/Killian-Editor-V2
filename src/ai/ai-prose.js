// ไฟล์ฉากของ Killian เก็บ **หนึ่งบรรทัด = หนึ่งย่อหน้า** (ตัวแก้ไขเขียนแบบนี้เสมอ) · บรรทัดว่าง = ย่อหน้าว่างจริง ๆ
// โมเดลภาษาเขียนมาร์กดาวน์ทั่วไป: คั่นย่อหน้าด้วยบรรทัดว่าง → วางลงไฟล์ตรง ๆ = มีย่อหน้าว่างแทรกทุกย่อหน้า
// (เจอบนแอปจริง: ฉากที่ AI เขียนเว้นห่างเป็นสองเท่าของฉากที่ผู้ใช้พิมพ์ ทั้งบนจอ ใน PDF และใน .txt)
//
// ใช้กับร้อยแก้วเท่านั้น — บทภาพยนตร์ (fountain) บรรทัดว่างคือตัวคั่น element ห้ามแตะ

/**
 * บรรทัดว่างหนึ่งบรรทัดระหว่างย่อหน้า = ตัวคั่นย่อหน้า (ตัดทิ้ง) · ตั้งแต่สองบรรทัดว่างขึ้นไป = ผู้เขียนตั้งใจเว้น (เหลือหนึ่ง)
 * @param {string} text
 * @returns {string}
 */
export function aiProseText(text) {
  const s = String(text ?? '').replace(/\r\n?/g, '\n').replace(/[ \t]+$/gm, '');
  return s.replace(/\n{2,}/g, (m) => (m.length >= 3 ? '\n\n' : '\n')).replace(/^\n+|\n+$/g, '');
}

/**
 * [alpha.170 · บั๊ก 16] คำตอบที่มีแต่ JSON ว่าง (`[]` · `{}` · ครอบด้วยรั้วโค้ดได้) = "ไม่มีข้อสังเกต"
 * หน้าจอต้องขึ้นข้อความของโปรแกรม ไม่ใช่โชว์ `[]` ดิบใต้หัวข้อ "ความเห็นจาก AI"
 */
export function isEmptyJsonReply(text) {
  const s = String(text || '').trim().replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/, '').trim();
  return /^(\[\s*\]|\{\s*\})$/.test(s);
}

/** ต่อข้อความใหม่ท้ายเนื้อเดิมของฉากร้อยแก้ว — ขึ้นย่อหน้าใหม่ ไม่มีย่อหน้าว่างคั่น */
export function appendProse(body, add) {
  const a = aiProseText(add);
  const b = String(body ?? '').replace(/\s+$/, '');
  return b ? (a ? b + '\n' + a : b) : a;
}
