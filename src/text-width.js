// text-width.js — "ความยาวที่มองเห็นเป็นความกว้าง" ของข้อความ (alpha.82)
//
// ทั้งนิยาย (proseWrap) และบทภาพยนตร์ (wrapLines/splitText) ประมาณจำนวนบรรทัดจาก
// "จำนวนตัวอักษร ÷ ตัวอักษรต่อบรรทัด" — ซึ่งพังกับภาษาไทย เพราะสระบน/ล่างและวรรณยุกต์
// ซ้อนอยู่บนพยัญชนะ **ไม่กินความกว้างเลย** แต่ถูกนับเป็นตัวอักษรเต็มตัวเท่ากับ ก ข ค
// ข้อความนิยาย/บทไทยทั่วไปมีอักขระพวกนี้ 20–30% ของความยาว → ประมาณบรรทัดเกินจริงพอ ๆ กัน
// ผลคือหน้าถูกตัดเร็วเกินไป เหลือช่องว่างท้ายหน้าเป็นสิบบรรทัด
//
// วัดจากการวาดจริงของบทไทย (Courier Thai Mono 12pt กว้าง 6") — ตัวเลขก่อน/หลังแก้:
//   168 ตัวอักษร (มองเห็น 122) → เดา 4 บรรทัด · จริง 3
//   125 ตัวอักษร (มองเห็น 100) → เดา 3 บรรทัด · จริง 2
//    65 ตัวอักษร (มองเห็น  50) → เดา 2 บรรทัด · จริง 1
// รวมทั้งหน้าเดาเกินจริง 45.8% — พอใช้ความยาวที่มองเห็น ตรงทั้งสามบล็อก
//
// อยู่แยกเป็นไฟล์ของตัวเองเพราะ prose-format.js import จาก sp-format.js อยู่แล้ว
// ถ้าเก็บไว้ฝั่งใดฝั่งหนึ่งแล้วให้อีกฝั่งดึงไปใช้ จะกลายเป็น import วนกลับ

/**
 * อักขระที่ "ไม่กินความกว้าง"
 *
 * ไทย: U+0E31 (ั), U+0E34–U+0E3A (ิ ี ึ ื ุ ู ฺ), U+0E47–U+0E4E (็ ่ ้ ๊ ๋ ์ ํ ๎)
 * เติม combining mark สากลไว้ด้วย เผื่อข้อความละติน/เวียดนามที่ใส่สระแยก
 */
export const ZERO_WIDTH_RE = new RegExp(
  '[' +
  '\\u0E31\\u0E34-\\u0E3A\\u0E47-\\u0E4E' +   // ไทย: สระบน/ล่าง · ไม้ไต่คู้ · วรรณยุกต์ · การันต์
  '\\u0300-\\u036F\\u0483-\\u0489' +          // combining ละติน/ซีริลลิก
  '\\u0591-\\u05BD\\u064B-\\u065F\\u0670' +   // ฮีบรู/อาหรับ
  '\\u200B-\\u200D\\uFEFF' +                  // ช่องว่างความกว้างศูนย์
  ']', 'g');

/** ความยาวที่ "มองเห็นเป็นความกว้าง" ของข้อความ (ตัดอักขระซ้อนที่กว้าง 0 ออก) */
export function visualLength(text) {
  return String(text ?? '').replace(ZERO_WIDTH_RE, '').length;
}
